const STORAGE_KEY = "cleanspot_reports_v1";
const LANGUAGE_KEY = "cleanspot_language";

let currentLanguage = localStorage.getItem(LANGUAGE_KEY) || "en";

if (!translations[currentLanguage]) {
  currentLanguage = "en";
}

const reportForm = document.getElementById("reportForm");
const reportList = document.getElementById("reportList");
const languageBtn = document.getElementById("languageBtn");
const issuePhoto = document.getElementById("issuePhoto");
const photoPreviewContainer =
  document.getElementById("photoPreviewContainer");
const photoPreview = document.getElementById("photoPreview");
const formMessage = document.getElementById("formMessage");
const searchReports = document.getElementById("searchReports");
const filterStatus = document.getElementById("filterStatus");

// Load saved reports
function getReports() {
  try {
    const saved = JSON.parse(
      localStorage.getItem(STORAGE_KEY) || "[]"
    );

    if (!Array.isArray(saved)) return [];

    return saved.map((report, index) => ({
      ...report,
      id: String(report.id || `old-${index}-${Date.now()}`),
      status: report.status === "Resolved" ? "Resolved" : "Pending",
      category: String(report.category || "Other"),
      location: String(report.location || ""),
      details: String(report.details || ""),
      photo: typeof report.photo === "string" ? report.photo : "",
      createdAt: report.createdAt || ""
    }));
  } catch {
    return [];
  }
}

let reports = getReports();

// Save reports in browser storage
function saveReports() {
  localStorage.setItem(
    STORAGE_KEY,
    JSON.stringify(reports)
  );
}

// Safely display user-entered text
function escapeHTML(value) {
  return String(value ?? "").replace(/[&<>"']/g, character => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    '"': "&quot;",
    "'": "&#39;"
  })[character]);
}

// Display translated status
function statusText(status) {
  return status === "Resolved"
    ? translations[currentLanguage].resolved
    : translations[currentLanguage].pending;
}

// Update dashboard counts
function updateStats() {
  const total = reports.length;

  const resolved = reports.filter(
    report => report.status === "Resolved"
  ).length;

  const pending = total - resolved;

  const totalCount = document.getElementById("totalCount");
  const pendingCount = document.getElementById("pendingCount");
  const resolvedCount = document.getElementById("resolvedCount");

  if (totalCount) totalCount.textContent = total;
  if (pendingCount) pendingCount.textContent = pending;
  if (resolvedCount) resolvedCount.textContent = resolved;
}

// Search, filter and display reports
function renderReports() {
  if (!reportList) return;

  const searchText = (searchReports?.value || "")
    .trim()
    .toLocaleLowerCase();

  const selectedStatus = filterStatus?.value || "All";

  const filteredReports = reports.filter(report => {
    const searchableText = [
      report.category,
      report.location,
      report.details
    ].join(" ").toLocaleLowerCase();

    const matchesSearch = searchableText.includes(searchText);

    const matchesStatus =
      selectedStatus === "All" ||
      report.status === selectedStatus;

    return matchesSearch && matchesStatus;
  });

  if (reports.length === 0) {
    reportList.innerHTML = `
      <p class="no-reports">
        ${translations[currentLanguage].noReports}
      </p>
    `;

    updateStats();
    return;
  }

  if (filteredReports.length === 0) {
    reportList.innerHTML = `
      <p class="no-reports">
        ${translations[currentLanguage].noMatches}
      </p>
    `;

    updateStats();
    return;
  }

  reportList.innerHTML = filteredReports.map(report => {
    const resolved = report.status === "Resolved";

    const date = report.createdAt
      ? new Date(report.createdAt).toLocaleDateString(
          currentLanguage === "ta" ? "ta-IN" : "en-IN"
        )
      : "—";

    const photoHTML = report.photo
      ? `
        <img
          src="${escapeHTML(report.photo)}"
          alt="${escapeHTML(
            translations[currentLanguage].photoPreviewTitle
          )}"
          class="report-photo"
        >
      `
      : "";

    return `
      <article class="report-card" data-id="${escapeHTML(report.id)}">

        <div class="report-card-header">
          <h3>${escapeHTML(report.category)}</h3>

          <span class="report-status ${resolved ? "resolved" : "pending"}">
            ${statusText(report.status)}
          </span>
        </div>

        <p>
          <strong>${translations[currentLanguage].location}:</strong>
          ${escapeHTML(report.location)}
        </p>

        <p>
          <strong>${translations[currentLanguage].details}:</strong>
          ${escapeHTML(report.details)}
        </p>

        ${photoHTML}

        <p class="report-date">
          <small>
            ${translations[currentLanguage].reportedOn}: ${escapeHTML(date)}
          </small>
        </p>

        <div class="report-actions">
          <button
            type="button"
            class="status-btn"
            data-action="toggle-status"
            data-id="${escapeHTML(report.id)}"
          >
            ${
              resolved
                ? translations[currentLanguage].markPending
                : translations[currentLanguage].markResolved
            }
          </button>

          <button
            type="button"
            class="delete-btn"
            data-action="delete"
            data-id="${escapeHTML(report.id)}"
          >
            ${translations[currentLanguage].delete}
          </button>
        </div>

      </article>
    `;
  }).join("");

  updateStats();
}

// Translate the page
function applyLanguage() {
  const text = translations[currentLanguage];

  document.documentElement.lang = currentLanguage;

  document.querySelectorAll("[data-i18n]").forEach(element => {
    const key = element.dataset.i18n;

    if (text[key] !== undefined) {
      element.textContent = text[key];
    }
  });

  document.querySelectorAll("[data-i18n-html]").forEach(element => {
    const key = element.dataset.i18nHtml;

    if (text[key] !== undefined) {
      element.innerHTML = text[key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
    const key = element.dataset.i18nPlaceholder;

    if (text[key] !== undefined) {
      element.placeholder = text[key];
    }
  });

  if (languageBtn) {
    languageBtn.textContent = text.langButton;
  }

  renderReports();
}

// Language toggle
languageBtn?.addEventListener("click", () => {
  currentLanguage = currentLanguage === "en" ? "ta" : "en";

  localStorage.setItem(LANGUAGE_KEY, currentLanguage);

  applyLanguage();
});

// Photo preview and validation
issuePhoto?.addEventListener("change", () => {
  const file = issuePhoto.files?.[0];

  if (!file) {
    if (photoPreviewContainer) {
      photoPreviewContainer.hidden = true;
    }

    if (photoPreview) {
      photoPreview.removeAttribute("src");
    }

    return;
  }

  if (!file.type.startsWith("image/")) {
    alert(translations[currentLanguage].invalidPhoto);
    issuePhoto.value = "";

    if (photoPreviewContainer) {
      photoPreviewContainer.hidden = true;
    }

    return;
  }

  if (file.size > 5 * 1024 * 1024) {
    alert(translations[currentLanguage].photoTooLarge);
    issuePhoto.value = "";

    if (photoPreviewContainer) {
      photoPreviewContainer.hidden = true;
    }

    return;
  }

  const reader = new FileReader();

  reader.onload = event => {
    if (photoPreview) {
      photoPreview.src = event.target.result;
    }

    if (photoPreviewContainer) {
      photoPreviewContainer.hidden = false;
    }
  };

  reader.onerror = () => {
    alert("Could not read this image. Please try again.");
  };

  reader.readAsDataURL(file);
});

// Submit a new report
reportForm?.addEventListener("submit", event => {
  event.preventDefault();

  const category = document.getElementById("category").value.trim();
  const location = document.getElementById("location").value.trim();
  const details = document.getElementById("details").value.trim();
  const file = issuePhoto?.files?.[0];

  if (!category || !location || !details) {
    reportForm.reportValidity();
    return;
  }

  if (file && !file.type.startsWith("image/")) {
    alert(translations[currentLanguage].invalidPhoto);
    return;
  }

  if (file && file.size > 5 * 1024 * 1024) {
    alert(translations[currentLanguage].photoTooLarge);
    return;
  }

  function addReport(photoData = "") {
    const newReport = {
      id: `${Date.now()}-${Math.random().toString(36).slice(2, 9)}`,
      category,
      location,
      details,
      photo: photoData,
      status: "Pending",
      createdAt: new Date().toISOString()
    };

    reports.unshift(newReport);

    try {
      saveReports();
    } catch (error) {
      reports.shift();

      alert(translations[currentLanguage].storageError);
      return;
    }

    reportForm.reset();

    if (photoPreviewContainer) {
      photoPreviewContainer.hidden = true;
    }

    if (photoPreview) {
      photoPreview.removeAttribute("src");
    }

    if (formMessage) {
      formMessage.textContent =
        translations[currentLanguage].reportSuccess;

      formMessage.style.color = "#166534";
    }

    if (searchReports) searchReports.value = "";
    if (filterStatus) filterStatus.value = "All";

    renderReports();

    document.getElementById("recentReports")?.scrollIntoView({
      behavior: "smooth",
      block: "start"
    });
  }

  if (file) {
    const reader = new FileReader();

    reader.onload = event => {
      addReport(event.target.result);
    };

    reader.onerror = () => {
      alert("Could not read this image. Please try again.");
    };

    reader.readAsDataURL(file);
  } else {
    addReport();
  }
});

// Change report status or delete a report
reportList?.addEventListener("click", event => {
  const button = event.target.closest("button[data-action]");

  if (!button) return;

  const reportId = button.dataset.id;
  const action = button.dataset.action;

  const reportIndex = reports.findIndex(
    item => item.id === reportId
  );

  if (reportIndex === -1) return;

  // Pending <-> Resolved
  if (action === "toggle-status") {
    const oldStatus = reports[reportIndex].status;

    reports[reportIndex].status =
      oldStatus === "Resolved" ? "Pending" : "Resolved";

    try {
      saveReports();
    } catch {
      reports[reportIndex].status = oldStatus;

      alert(translations[currentLanguage].saveError);
      return;
    }

    renderReports();
  }

  // Delete report after confirmation
  if (action === "delete") {
    if (!confirm(translations[currentLanguage].confirmDelete)) {
      return;
    }

    const removedReport = reports[reportIndex];

    reports.splice(reportIndex, 1);

    try {
      saveReports();
    } catch {
      reports.splice(reportIndex, 0, removedReport);

      alert(translations[currentLanguage].saveError);
      renderReports();
      return;
    }

    renderReports();
  }
});

// Search as the user types
searchReports?.addEventListener("input", renderReports);

// Filter by status
filterStatus?.addEventListener("change", renderReports);

// Display saved reports when the page opens
applyLanguage();
